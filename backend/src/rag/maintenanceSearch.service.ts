import { withTenantTransaction } from "../db/tenantTransaction";

const EMBEDDING_DIMENSIONS = 1536;

export interface MaintenanceChunkMatch {
  id: string;
  documentId: string;
  content: string;
  metadata: Record<string, unknown>;
  similarity: number;
}

// Checks the vector has 1536 valid numbers.
export function validateEmbedding(embedding: unknown): asserts embedding is number[] {
  if (
    !Array.isArray(embedding) ||
    embedding.length !== EMBEDDING_DIMENSIONS ||
    embedding.some((value: unknown) => typeof value !== "number" || !Number.isFinite(value))
  ) {
    throw new TypeError("Embedding must contain exactly 1536 finite numbers");
  }
}

// The caller supplies an embedding generated by its configured embeddings provider.
// Tenant context is set transaction-locally and reinforced by PostgreSQL RLS.
// Finds the closest document chunks for one tenant.
export async function searchMaintenanceChunks(input: {
  tenantId: string;
  embedding: readonly number[];
  limit?: number;
}): Promise<MaintenanceChunkMatch[]> {
  const { tenantId, embedding, limit = 5 } = input;
  validateEmbedding(embedding);
  const take = Math.min(Math.max(Number(limit) || 5, 1), 20);
  const vector = `[${embedding.join(",")}]`;
  return withTenantTransaction(tenantId, (tx) =>
    tx.$queryRawUnsafe<MaintenanceChunkMatch[]>(
      `SELECT id, "documentId", content, metadata,
            1 - (embedding <=> $1::vector) AS similarity
       FROM "MaintenanceChunk"
      WHERE "tenantId" = $2::uuid
      ORDER BY embedding <=> $1::vector
      LIMIT $3`,
      vector,
      tenantId,
      take
    )
  );
}
